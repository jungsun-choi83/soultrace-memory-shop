export function normalizeLang(value) {
  return value === 'en' ? 'en' : 'ko';
}
export function readLang() {
  try {
    return normalizeLang(localStorage.getItem(SHOP.langKey));
  } catch {
    return 'ko';
  }
}
export function persistLang(lang) {
  try { localStorage.setItem(SHOP.langKey, normalizeLang(lang)); } catch { /* Privacy mode: keep in-memory language. */ }
}

