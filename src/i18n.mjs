export function localizedProduct(product, lang) {
  if (normalizeLang(lang) !== 'en') return product;
  const copy = PRODUCT_EN[product.id];
  if (!copy) return product;
  return {
    ...product,
    name: copy.name,
    short: copy.short,
    description: copy.description,
    details: copy.details,
    variants: product.variants.map(variant => ({ ...variant, name: copy.variantNames[variant.id] ?? variant.name })),
  };
}

